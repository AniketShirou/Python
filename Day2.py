#Data Types in Python

################# Basic Types ###############
#integer
print(4)

#float
print(4.52)

#complex
print(4+5j)
print(1.4j)

#boolean
print(True)
print(False)


############### Container Type ##############
#List
a = [1,2,3]
print(a)

#Tuple
a = (1,2,3)
print(a)

#Sets
a = {1,2,3,1,2,3}
print(a)

#dictionary
a = {
   "Name": "aniket",
   "Age": 21,
   "Company": "Alteryx"
}

print(a)


